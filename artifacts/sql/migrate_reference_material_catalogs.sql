WITH unit_mapping(raw_value, symbol) AS (
    VALUES
        ('Microgram', 'µg'), ('µg', 'µg'), ('ug', 'µg'),
        ('Milligram', 'mg'), ('mg', 'mg'),
        ('Gram', 'g'), ('g', 'g'),
        ('Kilogram', 'kg'), ('kg', 'kg'),
        ('Milliliter', 'mL'), ('mL', 'mL'), ('ml', 'mL'),
        ('Liter', 'L'), ('L', 'L'), ('l', 'L')
)
UPDATE public.reference_materials material
SET unit_id = catalog.id
FROM unit_mapping mapping
JOIN public.reference_units catalog ON lower(catalog.symbol) = lower(mapping.symbol)
WHERE material.unit_id IS NULL
  AND lower(btrim(material.unit)) = lower(mapping.raw_value);

UPDATE public.reference_materials material
SET location_id = catalog.id
FROM public.reference_locations catalog
WHERE material.location_id IS NULL
  AND catalog.is_active
  AND lower(btrim(material.storage_location)) = lower(catalog.name);

WITH temperature_mapping(raw_value, label) AS (
    VALUES
        ('20', '20 °C'), ('20.0', '20 °C'), ('20 °C', '20 °C'), ('20°C', '20 °C'),
        ('10', '10 °C'), ('10.0', '10 °C'), ('10 °C', '10 °C'), ('10°C', '10 °C'),
        ('4', '4 °C'), ('4.0', '4 °C'), ('4 °C', '4 °C'), ('4°C', '4 °C'),
        ('-4', '-4 °C'), ('-4.0', '-4 °C'), ('-4 °C', '-4 °C'), ('-4°C', '-4 °C'),
        ('-20', '-20 °C'), ('-20.0', '-20 °C'), ('-20 °C', '-20 °C'), ('-20°C', '-20 °C'),
        ('T ambiente', 'Temperatura ambiente'),
        ('Temperatura ambiente', 'Temperatura ambiente')
