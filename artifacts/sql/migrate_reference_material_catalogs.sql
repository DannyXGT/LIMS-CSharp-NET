SELECT 'method' AS field, method AS unmapped_value, count(*) AS rows
FROM public.reference_materials WHERE method_id IS NULL GROUP BY method
UNION ALL
SELECT 'unit', unit, count(*) FROM public.reference_materials WHERE unit_id IS NULL GROUP BY unit
UNION ALL
SELECT 'storage_location', storage_location, count(*)
FROM public.reference_materials WHERE location_id IS NULL GROUP BY storage_location
UNION ALL
SELECT 'storage_conditions', storage_conditions, count(*)
FROM public.reference_materials
WHERE legacy_id IS NOT NULL AND storage_temperature_id IS NULL
GROUP BY storage_conditions
ORDER BY field, unmapped_value;

SELECT id, legacy_id, method, unit, storage_location, storage_conditions,
       method_id, unit_id, location_id, storage_temperature, storage_temperature_id
FROM public.reference_materials
WHERE method_id IS NULL
   OR unit_id IS NULL
   OR location_id IS NULL
   OR storage_temperature IS NULL
   OR (legacy_id IS NOT NULL AND storage_temperature_id IS NULL)
ORDER BY legacy_id NULLS LAST, id;

DO $mapping_guard$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.reference_materials
        WHERE method_id IS NULL
           OR unit_id IS NULL
           OR location_id IS NULL
           OR storage_temperature IS NULL
           OR (legacy_id IS NOT NULL AND storage_temperature_id IS NULL)
    ) THEN
        RAISE EXCEPTION 'Unmapped reference_materials rows remain; transaction aborted';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.reference_materials material
        JOIN public.reference_methods method ON method.id = material.method_id
        WHERE lower(btrim(material.method)) <> lower(method.name)
    ) THEN
        RAISE EXCEPTION 'method mapping mismatch detected';
    END IF;

    -- BEGIN UNIT MAPPING GUARD
    -- Native records use unit_id; the legacy text is not written by the .NET model.
    -- Every record must resolve its catalog ID. Only imported rows require a
    -- comparison with the historical text, matching the post-migration validator.
    IF EXISTS (
        SELECT 1
        FROM public.reference_materials material
        LEFT JOIN public.reference_units unit ON unit.id = material.unit_id
        WHERE unit.id IS NULL
           OR (material.legacy_id IS NOT NULL
               AND lower(unit.symbol) IS DISTINCT FROM CASE lower(btrim(material.unit))
                   WHEN 'microgram' THEN 'µg' WHEN 'µg' THEN 'µg' WHEN 'ug' THEN 'µg'
                   WHEN 'milligram' THEN 'mg' WHEN 'mg' THEN 'mg'
                   WHEN 'gram' THEN 'g' WHEN 'g' THEN 'g'
                   WHEN 'kilogram' THEN 'kg' WHEN 'kg' THEN 'kg'
                   WHEN 'milliliter' THEN 'ml' WHEN 'ml' THEN 'ml'
                   WHEN 'liter' THEN 'l' WHEN 'l' THEN 'l'
                   ELSE NULL
               END)
    ) THEN
        RAISE EXCEPTION 'unit mapping mismatch detected';
    END IF;
    -- END UNIT MAPPING GUARD

    IF EXISTS (
        SELECT 1
        FROM public.reference_materials material
        JOIN public.reference_locations location ON location.id = material.location_id
        WHERE lower(btrim(material.storage_location)) <> lower(location.name)
    ) THEN
        RAISE EXCEPTION 'location mapping mismatch detected';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.reference_materials material
        JOIN public.reference_storage_temperatures temperature
          ON temperature.id = material.storage_temperature_id
        WHERE NOT (
            (lower(btrim(material.storage_conditions)) IN ('t ambiente', 'temperatura ambiente')
             AND temperature.is_ambient)
            OR (lower(btrim(material.storage_conditions)) IN ('20', '20.0', '20 °c', '20°c')
                AND NOT temperature.is_ambient AND temperature.temperature_c = 20.00)
            OR (lower(btrim(material.storage_conditions)) IN ('10', '10.0', '10 °c', '10°c')
                AND NOT temperature.is_ambient AND temperature.temperature_c = 10.00)
            OR (lower(btrim(material.storage_conditions)) IN ('4', '4.0', '4 °c', '4°c')
                AND NOT temperature.is_ambient AND temperature.temperature_c = 4.00)
            OR (lower(btrim(material.storage_conditions)) IN ('-4', '-4.0', '-4 °c', '-4°c')
                AND NOT temperature.is_ambient AND temperature.temperature_c = -4.00)
            OR (lower(btrim(material.storage_conditions)) IN ('-20', '-20.0', '-20 °c', '-20°c')
                AND NOT temperature.is_ambient AND temperature.temperature_c = -20.00)
        )
    ) THEN
        RAISE EXCEPTION 'storage temperature mapping mismatch detected';
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.reference_materials
        WHERE legacy_id IS NULL
          AND (created_by_user_id IS NULL OR updated_by_user_id IS NULL)
    ) THEN
        RAISE EXCEPTION 'Native reference material without required audit actors detected';
    END IF;
END
$mapping_guard$;

