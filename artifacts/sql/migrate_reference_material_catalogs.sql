UPDATE public.reference_materials material
SET storage_temperature_id = catalog.id
FROM temperature_mapping mapping
JOIN public.reference_storage_temperatures catalog ON lower(catalog.label) = lower(mapping.label)
WHERE material.storage_temperature_id IS NULL
  AND lower(btrim(material.storage_conditions)) = lower(mapping.raw_value);

