DO $preflight$
DECLARE
    missing_columns text;
BEGIN
    IF to_regclass('public.reference_materials') IS NULL THEN
        RAISE EXCEPTION 'public.reference_materials does not exist';
    END IF;

    SELECT string_agg(expected.column_name, ', ' ORDER BY expected.column_name)
      INTO missing_columns
      FROM (VALUES
          ('id'), ('legacy_id'), ('name'), ('cas_number'), ('catalog_number'),
          ('method'), ('purity_percent'), ('lot'), ('brand'), ('received_date'),
          ('expiration_date'), ('presentation_quantity'), ('unit'), ('package_count'),
          ('available_quantity'), ('storage_conditions'), ('storage_location'), ('status'),
          ('created_by_user_id'), ('created_at'), ('updated_by_user_id'), ('updated_at'),
          ('archived_by_user_id'), ('archived_at'), ('archive_reason'),
          ('replaced_by_material_id'), ('version')
      ) AS expected(column_name)
      WHERE NOT EXISTS (
          SELECT 1
          FROM information_schema.columns actual
          WHERE actual.table_schema = 'public'
            AND actual.table_name = 'reference_materials'
            AND actual.column_name = expected.column_name
      );

    IF missing_columns IS NOT NULL THEN
        RAISE EXCEPTION 'reference_materials is missing expected columns: %', missing_columns;
    END IF;

    IF (SELECT format_type(a.atttypid, a.atttypmod)
        FROM pg_attribute a
        WHERE a.attrelid = 'public.reference_materials'::regclass
          AND a.attname = 'purity_percent'
          AND NOT a.attisdropped) <> 'numeric(7,4)' THEN
        RAISE EXCEPTION 'purity_percent must be numeric(7,4) before migration';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_attribute a
        WHERE a.attrelid = 'public.reference_materials'::regclass
          AND a.attname IN ('presentation_quantity', 'available_quantity')
          AND NOT a.attisdropped
          AND format_type(a.atttypid, a.atttypmod) <> 'numeric(18,6)'
    ) THEN
        RAISE EXCEPTION 'presentation_quantity and available_quantity must be numeric(18,6)';
    END IF;

    IF (SELECT format_type(a.atttypid, a.atttypmod)
        FROM pg_attribute a
        WHERE a.attrelid = 'public.reference_materials'::regclass
          AND a.attname = 'package_count'
          AND NOT a.attisdropped) <> 'integer' THEN
        RAISE EXCEPTION 'package_count must be integer before migration';
    END IF;

    RAISE NOTICE 'Preflight database=%, schema=%, reference_materials rows=%',
        current_database(), current_schema(), (SELECT count(*) FROM public.reference_materials);
END
$preflight$;

